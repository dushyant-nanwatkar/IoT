"""
Sentinel Laptop Core - High-Performance Thread-Safe Frame Ring Buffer
Decouples 30 FPS H.264 hardware decoding from 10-15 Hz RTX 5060 AI inference.
"""

import time
import threading
from typing import Optional, Tuple, Dict, Any, List
import numpy as np


class FrameRingBuffer:
    """
    Circular ring buffer optimized for zero-copy reference passing and
    ultra-low latency synchronization between H.264 decoders, the GPU AI
    worker thread, and WebSocket client broadcasters.
    """

    def __init__(self, capacity: int = 15):
        self.capacity = capacity
        self.lock = threading.Lock()
        self.new_frame_cond = threading.Condition(self.lock)

        # Raw frames from H.264 decoder
        self.raw_frames: List[Optional[np.ndarray]] = [None] * capacity
        self.raw_timestamps: List[int] = [0] * capacity
        self.write_idx: int = 0
        self.total_frames_received: int = 0

        # AI-Annotated latest frame with HUD overlay
        self.annotated_frame: Optional[np.ndarray] = None
        self.annotated_jpeg_cache: Optional[bytes] = None
        self.annotated_timestamp_ms: int = 0
        self.latest_detections: Dict[str, Any] = {}

        # FPS calculation
        self.fps_lock = threading.Lock()
        self.fps_timestamps: List[float] = []
        self.current_fps: float = 0.0

        # Phone Kiosk Screen Preview buffer (Channel 0x03)
        self.kiosk_screen_bytes: Optional[bytes] = None
        self.kiosk_screen_timestamp: float = 0.0

    def push_raw_frame(self, frame: np.ndarray, timestamp_ms: int = 0) -> None:
        """
        Push a newly decoded BGR frame from PyAV into the circular buffer.
        Notifies all waiting consumers (AI worker & streaming tasks).
        """
        now = time.time()
        with self.new_frame_cond:
            self.raw_frames[self.write_idx] = frame
            self.raw_timestamps[self.write_idx] = timestamp_ms or int(now * 1000)
            self.write_idx = (self.write_idx + 1) % self.capacity
            self.total_frames_received += 1
            self.new_frame_cond.notify_all()

        # Update FPS calculation
        with self.fps_lock:
            self.fps_timestamps.append(now)
            cutoff = now - 1.0
            self.fps_timestamps = [t for t in self.fps_timestamps if t >= cutoff]
            self.current_fps = float(len(self.fps_timestamps))

    def get_latest_raw_frame(self) -> Tuple[Optional[np.ndarray], int]:
        """Fetch the most recent raw video frame without copying."""
        with self.lock:
            if self.total_frames_received == 0:
                return None, 0
            latest_idx = (self.write_idx - 1) % self.capacity
            return self.raw_frames[latest_idx], self.raw_timestamps[latest_idx]

    def wait_for_new_raw_frame(self, timeout: float = 0.1) -> Tuple[Optional[np.ndarray], int]:
        """
        Block until a new raw frame is decoded or timeout expires.
        Used by the dedicated GPU AI inference thread.
        """
        with self.new_frame_cond:
            if self.total_frames_received == 0:
                self.new_frame_cond.wait(timeout)
                if self.total_frames_received == 0:
                    return None, 0
            latest_idx = (self.write_idx - 1) % self.capacity
            return self.raw_frames[latest_idx], self.raw_timestamps[latest_idx]

    def push_annotated_frame(
        self,
        frame: np.ndarray,
        jpeg_bytes: Optional[bytes] = None,
        detections: Optional[Dict[str, Any]] = None,
        timestamp_ms: int = 0,
    ) -> None:
        """Store the HUD-annotated frame generated by the RTX 5060 AI pipeline."""
        with self.lock:
            self.annotated_frame = frame
            self.annotated_jpeg_cache = jpeg_bytes
            self.latest_detections = detections or {}
            self.annotated_timestamp_ms = timestamp_ms or int(time.time() * 1000)

    def get_latest_annotated_frame(self) -> Tuple[Optional[np.ndarray], Optional[bytes], Dict[str, Any]]:
        """Fetch the latest HUD-annotated frame and JPEG cache for WebSockets."""
        with self.lock:
            return self.annotated_frame, self.annotated_jpeg_cache, self.latest_detections

    def update_kiosk_screen(self, image_bytes: bytes) -> None:
        """Store the latest phone display mirror screenshot (Channel 0x03)."""
        with self.lock:
            self.kiosk_screen_bytes = image_bytes
            self.kiosk_screen_timestamp = time.time()

    def get_latest_kiosk_screen(self) -> Optional[bytes]:
        """Retrieve the latest phone screen mirror preview."""
        with self.lock:
            return self.kiosk_screen_bytes

    def get_fps(self) -> float:
        """Return the current decoder frame rate."""
        with self.fps_lock:
            return self.current_fps


# Global singleton ring buffer instance
frame_buffer = FrameRingBuffer(capacity=20)
